import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Alert,
  Autocomplete,
  Box,
  Button,
  Chip,
  CircularProgress,
  Container,
  Paper,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  TextField,
  Typography,
} from '@mui/material';
import {
  Refresh as RefreshIcon,
  Save as SaveIcon,
} from '@mui/icons-material';
import { contentAPI, recommendationAPI } from '../../services/api';

const RATING_LABELS = {
  all_ages: { label: 'All ages', color: 'success' },
  teen: { label: 'Teen (13+)', color: 'info' },
  adult: { label: 'Adult (18+)', color: 'warning' },
  blocked: { label: 'Blocked', color: 'error' },
};

const SOURCE_LABELS = {
  moderator: 'Set by a moderator',
  pipeline: 'Generated by AI moderation',
  none: 'No tags yet',
};

// Audience tags set the youngest group a post may reach; they are not topics
const AUDIENCE_LABELS = { child: 'Child', teen: 'Teen', '18_plus': '18+' };

const formatLabel = (value) => AUDIENCE_LABELS[value] || String(value || '').replace(/_/g, ' ');

const cleanTags = (values) => [...new Set(values.map((tag) => tag.trim().toLowerCase().replace(/\+/g, '_plus').replace(/[\s-]+/g, '_')).filter(Boolean))];

const tagsOf = (item) => [...new Set([...(item.audience_tags || []), item.category, ...(item.content_topics || [])].filter((tag) => tag && tag !== 'unknown'))];

const ContentTags = () => {
  const navigate = useNavigate();
  const [rows, setRows] = useState([]);
  const [knownTopics, setKnownTopics] = useState([]);
  const [drafts, setDrafts] = useState({});
  const [saving, setSaving] = useState(null);
  const [loading, setLoading] = useState(true);
  const [unavailable, setUnavailable] = useState(false);
  const [withheld, setWithheld] = useState(0);
  const [error, setError] = useState(null);
  const [success, setSuccess] = useState(null);

  // One row per post: the host's content list, with the recommender's tags where it has any
  const loadRows = async () => {
    setLoading(true);
    setError(null);
    try {
      const [tagged, all] = await Promise.all([
        recommendationAPI.listItemTags(),
        contentAPI.getAllContent(null, 200),
      ]);
      const byId = Object.fromEntries((tagged.items || []).map((item) => [item.item_id, item]));
      const merged = (all.content || []).map((content) => {
        const item = byId[content.content_id];
        delete byId[content.content_id];
        return {
          id: content.content_id,
          text: content.content_text || item?.content_text || '',
          status: item?.status || content.status || content.current_status,
          rating: item?.audience_rating || null,
          tags: item ? tagsOf(item) : [],
          source: item && tagsOf(item).length > 0 ? item.tags_source : 'none',
          escalated: Boolean(item?.is_escalated),
        };
      });
      // Items the recommender holds that are not in the host's list (for example beyond its limit)
      Object.values(byId).forEach((item) => {
        merged.push({
          id: item.item_id, text: item.content_text, status: item.status, rating: item.audience_rating,
          tags: tagsOf(item), source: tagsOf(item).length > 0 ? item.tags_source : 'none', escalated: item.is_escalated,
        });
      });
      setRows(merged);
      setKnownTopics([...(tagged.audience_tag_options || []), ...(tagged.known_topics || []), 'others']);
      setWithheld(tagged.escalated_withheld || 0);
      setDrafts({});
    } catch (err) {
      console.error('Error loading content tags:', err);
      if (err.response?.status === 404) {
        setUnavailable(true);
      } else {
        setError(err.response?.data?.detail || 'Failed to load content tags');
      }
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadRows();
  }, []);

  const handleSave = async (row) => {
    const topics = drafts[row.id];
    setSaving(row.id);
    setError(null);
    setSuccess(null);
    try {
      const updated = await recommendationAPI.updateItemTags(row.id, topics);
      setRows((current) => current.map((entry) => (entry.id === row.id
        ? { ...entry, tags: tagsOf(updated), source: updated.tags_source, rating: updated.audience_rating, status: updated.status || entry.status, escalated: updated.is_escalated }
        : entry)));
      setDrafts((current) => {
        const next = { ...current };
        delete next[row.id];
        return next;
      });
      setSuccess('Tags saved');
    } catch (err) {
      console.error('Error saving tags:', err);
      const detail = err.response?.data?.detail;
      setError(typeof detail === 'string' ? detail : 'Tags must be 1 to 10 short plain-text labels');
    } finally {
      setSaving(null);
    }
  };

  if (unavailable) {
    return (
      <Container maxWidth="md" sx={{ py: 4 }}>
        <Alert severity="info">Content tags are not enabled on this server. Set RECOMMENDATION_ENABLED=true in the backend and restart it.</Alert>
      </Container>
    );
  }

  return (
    <Container maxWidth="xl" sx={{ py: 4 }}>
      {/* Header */}
      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 3 }}>
        <Box>
          <Typography variant="h4" component="h1" fontWeight="bold" gutterBottom>
            Content Tags
          </Typography>
          <Typography variant="body1" color="text.secondary">
            View and set the tags of every post. Topic tags (science, coding, ...) decide which age groups a post suits; the first one is the category. Child, Teen and 18+ set the youngest group it may reach and can only make it stricter. A post reaches a feed only after it is approved.
          </Typography>
        </Box>
        <Button variant="outlined" startIcon={<RefreshIcon />} onClick={loadRows} disabled={loading}>
          Refresh
        </Button>
      </Box>

      {error && (
        <Alert severity="error" onClose={() => setError(null)} sx={{ mb: 3 }}>
          {error}
        </Alert>
      )}

      {success && (
        <Alert severity="success" onClose={() => setSuccess(null)} sx={{ mb: 3 }}>
          {success}
        </Alert>
      )}

      {withheld > 0 && (
        <Alert severity="warning" sx={{ mb: 3 }}>
          {withheld} high-risk {withheld === 1 ? 'post is' : 'posts are'} visible to senior roles only and not listed with tags here.
        </Alert>
      )}

      <Paper>
        {loading ? (
          <Box sx={{ display: 'flex', justifyContent: 'center', py: 6 }}>
            <CircularProgress />
          </Box>
        ) : (
          <TableContainer>
            <Table>
              <TableHead>
                <TableRow>
                  <TableCell><strong>Content</strong></TableCell>
                  <TableCell><strong>Status</strong></TableCell>
                  <TableCell><strong>Audience Rating</strong></TableCell>
                  <TableCell sx={{ minWidth: 340 }}><strong>Tags</strong></TableCell>
                  <TableCell><strong>Actions</strong></TableCell>
                </TableRow>
              </TableHead>
              <TableBody>
                {rows.map((row) => {
                  const draft = drafts[row.id];
                  const rating = RATING_LABELS[row.rating] || { label: 'Not rated', color: 'default' };
                  return (
                    <TableRow key={row.id} hover>
                      <TableCell sx={{ maxWidth: 320 }}>
                        <Typography variant="body2" noWrap title={row.text}>
                          {row.text || row.id}
                        </Typography>
                        {row.escalated && <Chip label="High-risk category" color="error" size="small" sx={{ mt: 0.5 }} />}
                      </TableCell>
                      <TableCell sx={{ textTransform: 'capitalize' }}>{formatLabel(row.status)}</TableCell>
                      <TableCell>
                        <Chip label={rating.label} color={rating.color} size="small" />
                      </TableCell>
                      <TableCell>
                        <Autocomplete
                          multiple
                          freeSolo
                          size="small"
                          options={knownTopics}
                          value={draft || row.tags}
                          onChange={(event, value) => {
                            setDrafts((current) => ({ ...current, [row.id]: cleanTags(value) }));
                            setSuccess(null);
                          }}
                          getOptionLabel={formatLabel}
                          renderTags={(value, getTagProps) =>
                            value.map((tag, index) => (
                              <Chip label={formatLabel(tag)} size="small" {...getTagProps({ index })} key={tag} />
                            ))
                          }
                          renderInput={(params) => <TextField {...params} placeholder="Add a tag" />}
                        />
                        <Typography variant="caption" color="text.secondary">
                          {SOURCE_LABELS[row.source] || SOURCE_LABELS.none}
                        </Typography>
                      </TableCell>
                      <TableCell>
                        <Box sx={{ display: 'flex', gap: 1 }}>
                          <Button
                            size="small"
                            variant="contained"
                            startIcon={saving === row.id ? <CircularProgress size={16} /> : <SaveIcon />}
                            disabled={!draft || draft.length === 0 || saving === row.id}
                            onClick={() => handleSave(row)}
                          >
                            {saving === row.id ? 'Saving...' : 'Save'}
                          </Button>
                          <Button size="small" variant="outlined" onClick={() => navigate(`/review/${row.id}`)}>
                            Review
                          </Button>
                        </Box>
                      </TableCell>
                    </TableRow>
                  );
                })}
              </TableBody>
            </Table>
          </TableContainer>
        )}

        {!loading && rows.length === 0 && (
          <Box sx={{ textAlign: 'center', py: 4 }}>
            <Typography variant="body1" color="text.secondary">
              No content has been submitted yet
            </Typography>
          </Box>
        )}
      </Paper>
    </Container>
  );
};

export default ContentTags;
